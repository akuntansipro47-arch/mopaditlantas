-- 4. Sequences for Auto-generating Numbers (Simulated with Functions)
-- Function to generate next number
CREATE OR REPLACE FUNCTION generate_entry_number() RETURNS TRIGGER AS $$
BEGIN
  NEW.entry_number := 'ENT-' || TO_CHAR(NOW(), 'YYYYMMDD') || '-' || substring(md5(random()::text) from 1 for 4);
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER set_entry_number
BEFORE INSERT ON vehicle_entries
FOR EACH ROW
WHEN (NEW.entry_number IS NULL)
EXECUTE FUNCTION generate_entry_number();

-- Function for Item Code
CREATE OR REPLACE FUNCTION generate_item_code() RETURNS TRIGGER AS $$
BEGIN
  NEW.item_code := 'BRG-' || substring(md5(random()::text) from 1 for 6);
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER set_item_code
BEFORE INSERT ON goods
FOR EACH ROW
WHEN (NEW.item_code IS NULL)
EXECUTE FUNCTION generate_item_code();

